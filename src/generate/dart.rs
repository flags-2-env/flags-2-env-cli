#[cfg(test)]
mod tests {
    use super::render;
    use crate::catalog::parse_catalog;

    #[test]
    fn dart_emits_static_const_keys() {
        let catalog = parse_catalog(
            r#"
[identity]
service = "vxl-sidecar"

[flags.bind]
env = "VXL_SIDECAR_BIND"
default = "127.0.0.1:9090"
"#,
            Some("SidecarEnv"),
        )
        .unwrap();
        let source = render(&catalog);
        assert!(source.contains("final class SidecarEnv"));
        assert!(source.contains("static const String service = 'vxl-sidecar';"));
        assert!(source.contains("static const String bind = 'VXL_SIDECAR_BIND';"));
        assert!(source.contains("static const String bindDefault = '127.0.0.1:9090';"));
    }

    #[test]
    fn dart_runtime_reads_bind_from_lookup() {
        let catalog = parse_catalog(
            r#"
[identity]
service = "vxl-sidecar"

[flags.bind]
env = "VXL_SIDECAR_BIND"
default = "127.0.0.1:9090"
"#,
            Some("SidecarEnv"),
        )
        .unwrap();
        let source = super::render_runtime(&catalog);
        assert!(source.contains("final class SidecarEnvValues"));
        assert!(source.contains("SidecarEnvValues loadFrom"));
        assert!(source.contains("SidecarEnvValues loadFromOs()"));
        assert!(source.contains("lookup('VXL_SIDECAR_BIND')"));
        assert!(source
            .contains("import 'env_io_stub.dart' if (dart.library.io) 'env_io.dart' as platform;"));
        assert!(!source.contains("import 'dart:io';"));
        assert!(source.contains("platform.osEnvironment()"));
        assert!(source.contains("_contractCheckString"));
        assert!(!source.contains("_parseBool"));
        assert!(!source.contains("_parseInt"));
        assert!(!source.contains("_parseDouble"));
        assert!(!source.contains("_contractCheckBool"));
        assert!(!source.contains("_contractCheckInt"));
        assert!(!source.contains("_contractCheckFloat"));
        assert!(!source.contains("_contractCheckJson"));
    }
}
